test('validatePAN: rejects a PAN with an invalid 4th character (entity code)', () => {
  const r = validatePAN('ABCXD1234E');
  assert.equal(r.valid, false);
  assert.match(r.reason, /entity-type code/);
});

test('validatePAN: rejects a structurally wrong PAN', () => {
  const r = validatePAN('ABC1234EFG');
  assert.equal(r.valid, false);
  assert.match(r.reason, /format/i);
});

test('validatePAN: entity code decoding covers all documented letters', () => {
  const map = {
    P: 'Individual (Person)',
    C: 'Company',
    H: 'Hindu Undivided Family (HUF)',
    A: 'Association of Persons (AOP)',
    B: 'Body of Individuals (BOI)',
    G: 'Government',
    J: 'Artificial Juridical Person',
    L: 'Local Authority',
    F: 'Firm / Limited Liability Partnership',
    T: 'Trust',
  };
  for (const [code, meaning] of Object.entries(map)) {
    const pan = `ABC${code}D1234E`;
    const r = validatePAN(pan);
    assert.equal(r.valid, true, `expected ${pan} to be valid`);
    assert.ok(r.reason.includes(meaning), `expected reason to mention "${meaning}" for code ${code}`);
  }
});

