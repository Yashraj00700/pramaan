test('runDeterministicChecks: returns empty arrays when nothing matches', () => {
  const result = runDeterministicChecks([
    { label: 'Full Name', value: 'John Doe' },
    { label: 'Address', value: '123 Main Street' },
  ]);
  assert.deepEqual(result.checks, []);
  assert.deepEqual(result.signals, []);
  assert.equal(result.hardFailures, 0);
});

test('runDeterministicChecks: detects a valid PAN by label and emits a PASS', () => {
  const result = runDeterministicChecks([{ label: 'PAN Number', value: 'ABCPD1234E' }]);
  assert.equal(result.checks.length, 1);
  assert.equal(result.checks[0].status, 'PASS');
  assert.equal(result.hardFailures, 0);
});

test('runDeterministicChecks: detects an invalid Aadhaar by label and counts a hard failure', () => {
  const result = runDeterministicChecks([{ label: 'Aadhaar No.', value: '435231857228' }]);
  assert.equal(result.checks.length, 1);
  assert.equal(result.checks[0].status, 'FAIL');
  assert.equal(result.hardFailures, 1);
});

test('runDeterministicChecks: detects an identifier via value-shape sniffing even with a vague label', () => {
  // Label gives no hint, but the value is structurally a PAN.
  const result = runDeterministicChecks([{ label: 'ID Number', value: 'ABCPD1234E' }]);
  assert.equal(result.checks.length, 1);
  assert.equal(result.checks[0].status, 'PASS');
});

test('runDeterministicChecks: flags a date of birth in the future', () => {
  const result = runDeterministicChecks([{ label: 'Date of Birth', value: '01/01/2099' }]);
  const dobCheck = result.checks.find((c) => c.check === 'Date-of-birth plausibility');
  assert.ok(dobCheck, 'expected a DOB plausibility check');
  assert.equal(dobCheck.status, 'FAIL');
  assert.equal(result.hardFailures, 1);
});

test('runDeterministicChecks: flags issue date after expiry date', () => {
  const result = runDeterministicChecks([
    { label: 'Issue Date', value: '01/01/2025' },
    { label: 'Expiry Date', value: '01/01/2020' },
  ]);
  const orderCheck = result.checks.find((c) => c.check === 'Issue/expiry date ordering');
  assert.ok(orderCheck, 'expected an issue/expiry ordering check');
  assert.equal(orderCheck.status, 'FAIL');
});

test('runDeterministicChecks: passes when issue date precedes expiry date', () => {
  const result = runDeterministicChecks([
    { label: 'Issue Date', value: '01/01/2020' },
    { label: 'Expiry Date', value: '01/01/2030' },
  ]);
  const orderCheck = result.checks.find((c) => c.check === 'Issue/expiry date ordering');
  assert.equal(orderCheck, undefined, 'should not emit a FAIL check when dates are consistent (no invented PASS either, per spec — only asserts problems it can prove)');
});

test('runDeterministicChecks: flags stated age inconsistent with date of birth', () => {
  const result = runDeterministicChecks([
    { label: 'Date of Birth', value: '01/01/2000' },
    { label: 'Age', value: '10' },
  ]);
  const ageCheck = result.checks.find((c) => c.check === 'Stated age vs date of birth');
  assert.ok(ageCheck, 'expected an age-vs-DOB check');
  assert.equal(ageCheck.status, 'FAIL');
});

test('runDeterministicChecks: does not invent a date check for an ambiguous/unparseable date', () => {
  const result = runDeterministicChecks([{ label: 'Date of Birth', value: 'not-a-date' }]);
  const dobCheck = result.checks.find((c) => c.check === 'Date-of-birth plausibility');
  assert.equal(dobCheck, undefined);
});

test('runDeterministicChecks: multiple identifiers accumulate hardFailures correctly', () => {
  const result = runDeterministicChecks([
    { label: 'PAN Number', value: 'ABCPD1234E' }, // valid -> 0
    { label: 'Aadhaar No.', value: '435231857228' }, // invalid -> 1
    { label: 'IFSC Code', value: 'HDFC1001234' }, // invalid (5th char) -> 1
    { label: 'Mobile Number', value: '9876543210' }, // valid -> 0
  ]);
  assert.equal(result.checks.length, 4);
  assert.equal(result.hardFailures, 2);
});
