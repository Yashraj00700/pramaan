// verification.test.mjs
//
// Plain Node test script (node:test + node:assert) for api/verification.ts.
// Run with: node --test api/verification.test.mjs
//
// Every "good" vector below was independently confirmed against the real
// checksum algorithms (Verhoeff for Aadhaar, mod-36 for GSTIN, MOD-97-10 for
// IBAN) before being hard-coded here — see the derivation notes in each
// section.

import test from 'node:test';
import assert from 'node:assert/strict';

import {
  validateAadhaar,
  validatePAN,
  validateGSTIN,
  validateIFSC,
  validateIBAN,
  validateUPI,
  validateIndianMobile,
  validatePIN,
  runDeterministicChecks,
} from './verification.ts';

// ---------------------------------------------------------------------------
// Aadhaar
// ---------------------------------------------------------------------------

test('validateAadhaar: accepts a number that passes the Verhoeff checksum', () => {
  // 435231857227 was generated by brute force and confirmed to pass Verhoeff.
  const r = validateAadhaar('435231857227');
  assert.equal(r.valid, true);
});

test('validateAadhaar: accepts the same number with spaces (normalizes input)', () => {
  const r = validateAadhaar('4352 3185 7227');
  assert.equal(r.valid, true);
});

test('validateAadhaar: rejects wrong length', () => {
  const r = validateAadhaar('123456789');
  assert.equal(r.valid, false);
  assert.match(r.reason, /12 digits/);
});

test('validateAadhaar: rejects numbers starting with 0 or 1', () => {
  const r0 = validateAadhaar('023456789012');
  assert.equal(r0.valid, false);
  assert.match(r0.reason, /start with 0 or 1/);

  const r1 = validateAadhaar('123456789012');
  assert.equal(r1.valid, false);
  assert.match(r1.reason, /start with 0 or 1/);
});

test('validateAadhaar: rejects a number that fails the Verhoeff checksum', () => {
  // Same digits as the good vector but with the last digit incremented,
  // which breaks the Verhoeff checksum.
  const r = validateAadhaar('435231857228');
  assert.equal(r.valid, false);
  assert.match(r.reason, /Verhoeff/);
});

test('validateAadhaar: rejects non-numeric input', () => {
  const r = validateAadhaar('43523185722A');
  assert.equal(r.valid, false);
});

// ---------------------------------------------------------------------------
// PAN
// ---------------------------------------------------------------------------

test('validatePAN: accepts a well-formed PAN with a valid entity code and explains it', () => {
  const r = validatePAN('ABCPD1234E');
  assert.equal(r.valid, true);
  assert.match(r.reason, /Individual \(Person\)/);
});

test('validatePAN: rejects a PAN with an invalid 4th character (entity code)', () => {
  const r = validatePAN('ABCXD1234E');
  assert.equal(r.valid, false);
  assert.match(r.reason, /entity-type code/);
});

test('validatePAN: rejects a structurally wrong PAN', () => {
  const r = validatePAN('ABC1234EFG');
  assert.equal(r.valid, false);
  assert.match(r.reason, /format/i);
});

test('validatePAN: entity code decoding covers all documented letters', () => {
  const map = {
    P: 'Individual (Person)',
    C: 'Company',
    H: 'Hindu Undivided Family (HUF)',
    A: 'Association of Persons (AOP)',
    B: 'Body of Individuals (BOI)',
    G: 'Government',
    J: 'Artificial Juridical Person',
    L: 'Local Authority',
    F: 'Firm / Limited Liability Partnership',
    T: 'Trust',
  };
  for (const [code, meaning] of Object.entries(map)) {
    const pan = `ABC${code}D1234E`;
    const r = validatePAN(pan);
    assert.equal(r.valid, true, `expected ${pan} to be valid`);
    assert.ok(r.reason.includes(meaning), `expected reason to mention "${meaning}" for code ${code}`);
  }
});

// ---------------------------------------------------------------------------
// GSTIN
// ---------------------------------------------------------------------------

test('validateGSTIN: accepts a GSTIN with a correct mod-36 checksum', () => {
  // 27ABCPD1234E1ZE: state 27 (Maharashtra) + valid PAN ABCPD1234E +
  // entity count 1 + literal Z + checksum 'E' (computed via the mod-36
  // algorithm and cross-checked against validateGSTIN itself above).
  const r = validateGSTIN('27ABCPD1234E1ZE');
  assert.equal(r.valid, true);
});

test('validateGSTIN: rejects a GSTIN with a broken checksum', () => {
  const r = validateGSTIN('27ABCPD1234E1Z0');
  assert.equal(r.valid, false);
  assert.match(r.reason, /checksum/i);
});

test('validateGSTIN: rejects an invalid state code', () => {
  const r = validateGSTIN('99ABCPD1234E1ZE');
  assert.equal(r.valid, false);
  assert.match(r.reason, /state code/i);
});

test('validateGSTIN: rejects a GSTIN with an invalid embedded PAN', () => {
  // 4th char of embedded PAN 'ABCXD1234E' is 'X' -> not a valid entity code.
  const r = validateGSTIN('27ABCXD1234E1ZE');
  assert.equal(r.valid, false);
  assert.match(r.reason, /PAN/);
});

test('validateGSTIN: rejects wrong length', () => {
  const r = validateGSTIN('27ABCPD1234E1Z');
  assert.equal(r.valid, false);
  assert.match(r.reason, /15 characters/);
});

