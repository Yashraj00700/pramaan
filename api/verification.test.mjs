test('validateAadhaar: accepts a number that passes the Verhoeff checksum', () => {
  // 435231857227 was generated by brute force and confirmed to pass Verhoeff.
  const r = validateAadhaar('435231857227');
  assert.equal(r.valid, true);
});

test('validateAadhaar: accepts the same number with spaces (normalizes input)', () => {
  const r = validateAadhaar('4352 3185 7227');
  assert.equal(r.valid, true);
});

test('validateAadhaar: rejects wrong length', () => {
  const r = validateAadhaar('123456789');
  assert.equal(r.valid, false);
  assert.match(r.reason, /12 digits/);
});

test('validateAadhaar: rejects numbers starting with 0 or 1', () => {
  const r0 = validateAadhaar('023456789012');
  assert.equal(r0.valid, false);
  assert.match(r0.reason, /start with 0 or 1/);

  const r1 = validateAadhaar('123456789012');
  assert.equal(r1.valid, false);
  assert.match(r1.reason, /start with 0 or 1/);
});

test('validateAadhaar: rejects a number that fails the Verhoeff checksum', () => {
  // Same digits as the good vector but with the last digit incremented,
  // which breaks the Verhoeff checksum.
  const r = validateAadhaar('435231857228');
  assert.equal(r.valid, false);
  assert.match(r.reason, /Verhoeff/);
});

test('validateAadhaar: rejects non-numeric input', () => {
  const r = validateAadhaar('43523185722A');
  assert.equal(r.valid, false);
});

